import { execute, isPostgres, query, sqliteHasColumn } from "./postgres.js";

export async function migrate() {
  const schema = `
    CREATE TABLE IF NOT EXISTS tenants (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS admins (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      name TEXT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS products (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      purchase_price NUMERIC(14, 2) NOT NULL,
      stock INTEGER NOT NULL DEFAULT 0,
      category TEXT,
      description TEXT,
      active INTEGER NOT NULL DEFAULT 1,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ
    );

    CREATE TABLE IF NOT EXISTS clients (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      phone TEXT,
      address TEXT,
      notes TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ
    );

    CREATE TABLE IF NOT EXISTS sales (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      client_id BIGINT REFERENCES clients(id) ON DELETE SET NULL,
      sale_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      total NUMERIC(14, 2) NOT NULL DEFAULT 0,
      notes TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS sale_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
      product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
      quantity INTEGER NOT NULL,
      unit_price NUMERIC(14, 2) NOT NULL,
      unit_cost NUMERIC(14, 2) NOT NULL DEFAULT 0,
      total_cost NUMERIC(14, 2) NOT NULL DEFAULT 0,
      subtotal NUMERIC(14, 2) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS inventory_lots (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
      quantity_received INTEGER NOT NULL,
      quantity_remaining INTEGER NOT NULL,
      unit_cost NUMERIC(14, 2) NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS sale_item_lots (
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      sale_item_id BIGINT NOT NULL REFERENCES sale_items(id) ON DELETE CASCADE,
      lot_id BIGINT NOT NULL REFERENCES inventory_lots(id) ON DELETE RESTRICT,
      quantity INTEGER NOT NULL,
      unit_cost NUMERIC(14, 2) NOT NULL,
      PRIMARY KEY (sale_item_id, lot_id)
    );

    CREATE TABLE IF NOT EXISTS suppliers (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      phone TEXT NOT NULL,
      notes TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ
    );

    CREATE TABLE IF NOT EXISTS supplier_products (
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,
      product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
      purchase_price NUMERIC(14, 2) NOT NULL,
      PRIMARY KEY (supplier_id, product_id)
    );

    CREATE TABLE IF NOT EXISTS purchase_orders (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
      supplier_name TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      received_at TIMESTAMPTZ
    );

    CREATE TABLE IF NOT EXISTS purchase_order_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
      order_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
      product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
      product_name TEXT NOT NULL,
      quantity INTEGER NOT NULL,
      unit_price NUMERIC(14, 2) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS company_settings (
      tenant_id BIGINT PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      rut TEXT NOT NULL,
      phone TEXT NOT NULL,
      address TEXT NOT NULL,
      updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    ALTER TABLE sale_items
      ADD COLUMN IF NOT EXISTS unit_cost NUMERIC(14, 2) NOT NULL DEFAULT 0;
    ALTER TABLE sale_items
      ADD COLUMN IF NOT EXISTS total_cost NUMERIC(14, 2) NOT NULL DEFAULT 0;

    ALTER TABLE tenants ENABLE ROW LEVEL SECURITY;
    ALTER TABLE admins ENABLE ROW LEVEL SECURITY;
    ALTER TABLE products ENABLE ROW LEVEL SECURITY;
    ALTER TABLE clients ENABLE ROW LEVEL SECURITY;
    ALTER TABLE sales ENABLE ROW LEVEL SECURITY;
    ALTER TABLE sale_items ENABLE ROW LEVEL SECURITY;
    ALTER TABLE inventory_lots ENABLE ROW LEVEL SECURITY;
    ALTER TABLE sale_item_lots ENABLE ROW LEVEL SECURITY;
    ALTER TABLE suppliers ENABLE ROW LEVEL SECURITY;
    ALTER TABLE supplier_products ENABLE ROW LEVEL SECURITY;
    ALTER TABLE purchase_orders ENABLE ROW LEVEL SECURITY;
    ALTER TABLE purchase_order_items ENABLE ROW LEVEL SECURITY;
    ALTER TABLE company_settings ENABLE ROW LEVEL SECURITY;

    CREATE INDEX IF NOT EXISTS idx_products_tenant ON products(tenant_id);
    CREATE INDEX IF NOT EXISTS idx_clients_tenant ON clients(tenant_id);
    CREATE INDEX IF NOT EXISTS idx_sales_tenant ON sales(tenant_id);
    CREATE INDEX IF NOT EXISTS idx_sale_items_tenant ON sale_items(tenant_id);
    CREATE INDEX IF NOT EXISTS idx_inventory_lots_product ON inventory_lots(tenant_id, product_id, id);
    CREATE INDEX IF NOT EXISTS idx_sale_item_lots_tenant ON sale_item_lots(tenant_id);
    CREATE INDEX IF NOT EXISTS idx_suppliers_tenant ON suppliers(tenant_id);
    CREATE INDEX IF NOT EXISTS idx_purchase_orders_tenant ON purchase_orders(tenant_id);
  `;

  if (isPostgres) {
    await query(schema);
    await query(`
      CREATE OR REPLACE FUNCTION prevent_duplicate_product_name()
      RETURNS trigger AS $$
      BEGIN
        PERFORM pg_advisory_xact_lock(
          hashtextextended(NEW.tenant_id::text || ':' || lower(trim(NEW.name)), 0)
        );
        IF EXISTS (
          SELECT 1 FROM products
          WHERE tenant_id = NEW.tenant_id
            AND lower(trim(name)) = lower(trim(NEW.name))
            AND id IS DISTINCT FROM NEW.id
        ) THEN
          RAISE EXCEPTION 'duplicate_product_name' USING ERRCODE = '23505';
        END IF;
        RETURN NEW;
      END;
      $$ LANGUAGE plpgsql
    `);
    await query("DROP TRIGGER IF EXISTS products_prevent_duplicate_name ON products");
    await query(`
      CREATE TRIGGER products_prevent_duplicate_name
      BEFORE INSERT OR UPDATE OF name, tenant_id ON products
      FOR EACH ROW EXECUTE FUNCTION prevent_duplicate_product_name()
    `);
  } else {
    const sqliteSchema = schema
      .replace(/BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g, "INTEGER PRIMARY KEY AUTOINCREMENT")
      .replace(/\bBIGINT\b/g, "INTEGER")
      .replace(/\bTIMESTAMPTZ\b/g, "TEXT")
      .replace(/ALTER TABLE \w+ ENABLE ROW LEVEL SECURITY;/g, "")
      .replace(/ALTER TABLE sale_items\s+ADD COLUMN IF NOT EXISTS unit_cost NUMERIC\(14, 2\) NOT NULL DEFAULT 0;/, "")
      .replace(/ALTER TABLE sale_items\s+ADD COLUMN IF NOT EXISTS total_cost NUMERIC\(14, 2\) NOT NULL DEFAULT 0;/, "");

    for (const statement of sqliteSchema.split(";").map((part) => part.trim()).filter(Boolean)) {
      await execute(statement);
    }

    if (!(await sqliteHasColumn("sale_items", "unit_cost"))) {
      await execute("ALTER TABLE sale_items ADD COLUMN unit_cost NUMERIC(14, 2) NOT NULL DEFAULT 0");
    }
    if (!(await sqliteHasColumn("sale_items", "total_cost"))) {
      await execute("ALTER TABLE sale_items ADD COLUMN total_cost NUMERIC(14, 2) NOT NULL DEFAULT 0");
    }
    await execute(`
      CREATE TRIGGER IF NOT EXISTS products_prevent_duplicate_name_insert
      BEFORE INSERT ON products
      WHEN EXISTS (
        SELECT 1 FROM products
        WHERE tenant_id = NEW.tenant_id AND lower(trim(name)) = lower(trim(NEW.name))
      )
      BEGIN
        SELECT RAISE(ABORT, 'duplicate_product_name');
      END
    `);
    await execute(`
      CREATE TRIGGER IF NOT EXISTS products_prevent_duplicate_name_update
      BEFORE UPDATE OF name, tenant_id ON products
      WHEN EXISTS (
        SELECT 1 FROM products
        WHERE tenant_id = NEW.tenant_id AND lower(trim(name)) = lower(trim(NEW.name))
          AND id <> OLD.id
      )
      BEGIN
        SELECT RAISE(ABORT, 'duplicate_product_name');
      END
    `);
  }

  await query(
    "UPDATE sale_items SET total_cost = quantity * unit_cost WHERE total_cost = 0 AND unit_cost <> 0"
  );
  await query(`
    INSERT INTO inventory_lots
      (tenant_id, product_id, quantity_received, quantity_remaining, unit_cost)
    SELECT p.tenant_id, p.id, p.stock, p.stock, p.purchase_price
    FROM products p
    WHERE p.stock > 0
      AND NOT EXISTS (
        SELECT 1 FROM inventory_lots l
        WHERE l.tenant_id = p.tenant_id AND l.product_id = p.id
      )
  `);
}
